param(
  [Parameter(Mandatory = $true)]
  [string]$SourceDirectory,

  [string]$OutputFile = (Join-Path $PSScriptRoot "..\app\freeApplicationIconData.ts")
)

$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Drawing

$resolvedSource = (Resolve-Path -LiteralPath $SourceDirectory).Path
$files = @(Get-ChildItem -LiteralPath $resolvedSource -Filter "*.png" -File | Sort-Object BaseName)
if ($files.Count -eq 0) {
  throw "No PNG icons were found in $resolvedSource"
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("// Generated by scripts/import-free-application-icons.ps1. Do not hand-edit pixel data.")
$lines.Add('export const FREE_APPLICATION_ICON_ATTRIBUTION="16x16 Free Application Icons by Aha-Soft (https://www.small-icons.com/stock-icons/16x16-free-application-icons.htm), licensed under CC BY 3.0 US: https://creativecommons.org/licenses/by/3.0/us/";')
$lines.Add("export const FREE_APPLICATION_ICON_DATA=[")
$ids = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)

foreach ($file in $files) {
  $bitmap = [System.Drawing.Bitmap]::new($file.FullName)
  try {
    if ($bitmap.Width -ne 16 -or $bitmap.Height -ne 16) {
      throw "$($file.Name) is $($bitmap.Width)x$($bitmap.Height); application icons must be exactly 16x16."
    }

    $bytes = [byte[]]::new(16 * 16 * 4)
    for ($y = 0; $y -lt 16; $y++) {
      for ($x = 0; $x -lt 16; $x++) {
        $pixel = $bitmap.GetPixel($x, $y)
        $offset = ($y * 16 + $x) * 4
        $bytes[$offset] = $pixel.R
        $bytes[$offset + 1] = $pixel.G
        $bytes[$offset + 2] = $pixel.B
        $bytes[$offset + 3] = $pixel.A
      }
    }

    $id = (($file.BaseName -creplace '([a-z0-9])([A-Z])', '$1_$2').ToLowerInvariant()) -replace '[^a-z0-9]+', '_'
    $id = $id.Trim('_')
    if (-not $ids.Add($id)) {
      throw "Duplicate normalized icon ID: $id"
    }
    $title = $file.BaseName.Replace('16x16', '').Trim()
    $titleJson = $title | ConvertTo-Json -Compress
    $encoded = [Convert]::ToBase64String($bytes)
    $lines.Add("  [`"$id`",$titleJson,`"$encoded`"],")
  }
  finally {
    $bitmap.Dispose()
  }
}

$lines.Add("] as const;")
$lines.Add("")
$outputDirectory = Split-Path -Parent $OutputFile
if (-not (Test-Path -LiteralPath $outputDirectory)) {
  New-Item -ItemType Directory -Path $outputDirectory | Out-Null
}
[System.IO.File]::WriteAllLines($OutputFile, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Output "Imported $($files.Count) full-RGBA application icons into $OutputFile"
