param(
  [Parameter(Mandatory = $true)]
  [string]$SourceDirectory,

  [string]$OutputFile = (Join-Path $PSScriptRoot "..\app\essentialIconData.ts")
)

$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Drawing

$resolvedSource = (Resolve-Path -LiteralPath $SourceDirectory).Path
$files = @(Get-ChildItem -LiteralPath $resolvedSource -Filter "*.png" -File | Sort-Object BaseName)
if ($files.Count -eq 0) {
  throw "No PNG icons were found in $resolvedSource"
}

$icons = @()
$paletteSet = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::OrdinalIgnoreCase)

foreach ($file in $files) {
  $bitmap = [System.Drawing.Bitmap]::new($file.FullName)
  try {
    if ($bitmap.Width -ne 16 -or $bitmap.Height -ne 16) {
      throw "$($file.Name) is $($bitmap.Width)x$($bitmap.Height); Essential icons must be exactly 16x16."
    }

    $pixels = [System.Collections.Generic.List[string]]::new()
    for ($y = 0; $y -lt 16; $y++) {
      for ($x = 0; $x -lt 16; $x++) {
        $pixel = $bitmap.GetPixel($x, $y)
        if ($pixel.A -eq 0) {
          $pixels.Add("")
          continue
        }
        if ($pixel.A -ne 255) {
          throw "$($file.Name) contains partial alpha at $x,$y; only transparent or opaque pixels are supported."
        }
        $color = "#{0:x2}{1:x2}{2:x2}" -f $pixel.R, $pixel.G, $pixel.B
        [void]$paletteSet.Add($color)
        $pixels.Add($color)
      }
    }
    $icons += [PSCustomObject]@{ Id = $file.BaseName; Pixels = $pixels }
  }
  finally {
    $bitmap.Dispose()
  }
}

$palette = @($paletteSet | Sort-Object)
if ($palette.Count -gt 255) {
  throw "The icon set contains $($palette.Count) colors; the compact format supports at most 255."
}
$indices = @{}
for ($index = 0; $index -lt $palette.Count; $index++) {
  $indices[$palette[$index]] = $index + 1
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("// Generated by scripts/import-essential-icons.ps1. Do not hand-edit pixel data.")
$lines.Add('export const ESSENTIAL_ICON_ATTRIBUTION="Icons Essential v1.2 by Crusenho Agus Hennihuno (https://crusenho.itch.io), licensed under CC BY 4.0: https://creativecommons.org/licenses/by/4.0/";')
$paletteJson = ($palette | ConvertTo-Json -Compress)
$lines.Add("export const ESSENTIAL_ICON_PALETTE=$paletteJson as const;")
$lines.Add("export const ESSENTIAL_ICON_DATA=[")
foreach ($icon in $icons) {
  $encoded = -join ($icon.Pixels | ForEach-Object { if ($_ -eq "") { "00" } else { "{0:x2}" -f $indices[$_] } })
  $id = (($icon.Id -creplace '([a-z0-9])([A-Z])', '$1_$2').ToLowerInvariant()) -replace '[^a-z0-9]+', '_'
  $lines.Add("  [`"$id`",`"$encoded`"],")
}
$lines.Add("] as const;")
$lines.Add("")

$outputDirectory = Split-Path -Parent $OutputFile
if (-not (Test-Path -LiteralPath $outputDirectory)) {
  New-Item -ItemType Directory -Path $outputDirectory | Out-Null
}
[System.IO.File]::WriteAllLines($OutputFile, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Output "Imported $($icons.Count) Essential icons with $($palette.Count) colors into $OutputFile"
